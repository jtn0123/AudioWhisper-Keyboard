// Writes one of crates/chars/src/tables/*.rs: how the platform it runs on answers Kotlin's Char
// functions, and the regex \s, for every UTF-16 unit. The answers differ between a computer's JVM
// and Android, whose java.lang.Character and regex come from ICU, so it is run on each;
// tools/generate-char-tables.sh does both.
//
// The flag bits must match those in crates/chars/src/lib.rs. Each flag is the Character call that
// the Kotlin function of the same name makes (kotlin-stdlib's CharJVM.kt).
public class JavaChars {
    static final int LETTER = 1;
    static final int DIGIT = 2;
    static final int LETTER_OR_DIGIT = 4;
    static final int UPPER = 8;
    static final int LOWER = 16;
    static final int SPACE = 32;
    static final int REGEX_SPACE = 64;

    static final java.util.regex.Pattern REGEX_S = java.util.regex.Pattern.compile("\\s");

    static int flags(char c) {
        int flags = 0;
        if (Character.isLetter(c)) flags |= LETTER;
        if (Character.isDigit(c)) flags |= DIGIT;
        if (Character.isLetterOrDigit(c)) flags |= LETTER_OR_DIGIT;
        if (Character.isUpperCase(c)) flags |= UPPER;
        if (Character.isLowerCase(c)) flags |= LOWER;
        // Kotlin's Char.isWhitespace().
        if (Character.isWhitespace(c) || Character.isSpaceChar(c)) flags |= SPACE;
        if (REGEX_S.matcher(String.valueOf(c)).matches()) flags |= REGEX_SPACE;
        return flags;
    }

    static String hex(int unit) {
        return String.format("0x%04X", unit);
    }

    static void field(String doc, String name, java.util.List<String> values) {
        System.out.println("    // " + doc);
        System.out.printf("    %s: &[%s],%n", name, String.join(", ", values));
    }

    static void mapping(String what, String name, java.util.function.IntUnaryOperator map) {
        var from = new java.util.ArrayList<String>();
        var to = new java.util.ArrayList<String>();
        for (int unit = 0; unit <= 0xFFFF; unit++) {
            int mapped = map.applyAsInt(unit);
            if (mapped != unit) {
                from.add(hex(unit));
                to.add(hex(mapped));
            }
        }
        field("The units whose " + what + " differs from themselves, ascending.", name + "_from", from);
        field("Their " + what + ", in the same order.", name + "_to", to);
    }

    /** Android's API level and ICU and Unicode versions, or the JVM's version. */
    static String platform() {
        try {
            int api = Class.forName("android.os.Build$VERSION").getField("SDK_INT").getInt(null);
            Object icu = Class.forName("android.icu.util.VersionInfo").getField("ICU_VERSION").get(null);
            Object unicode = Class.forName("android.icu.lang.UCharacter").getMethod("getUnicodeVersion").invoke(null);
            return "Android API " + api + " (ICU " + icu + ", Unicode " + unicode + ")";
        } catch (ReflectiveOperationException notAndroid) {
            return "Java " + System.getProperty("java.version");
        }
    }

    public static void main(String[] args) {
        var starts = new java.util.ArrayList<String>();
        var values = new java.util.ArrayList<String>();
        int previous = -1;
        for (int unit = 0; unit <= 0xFFFF; unit++) {
            int flags = flags((char) unit);
            if (flags != previous) {
                starts.add(hex(unit));
                values.add(Integer.toString(flags));
                previous = flags;
            }
        }
        System.out.println("//! Generated by tools/JavaChars.java on " + platform() + ". Don't edit;");
        System.out.println("//! run tools/generate-char-tables.sh.");
        System.out.println();
        System.out.println("use super::Tables;");
        System.out.println();
        System.out.println("pub(crate) static TABLES: Tables = Tables {");
        field("Where each run of units with the same flags starts, ascending from 0.", "flag_starts", starts);
        field("Each run's flags.", "flags", values);
        mapping("upper case (`Character.toUpperCase`)", "upper", unit -> Character.toUpperCase((char) unit));
        mapping("lower case (`Character.toLowerCase`)", "lower", unit -> Character.toLowerCase((char) unit));
        System.out.println("};");
    }
}
