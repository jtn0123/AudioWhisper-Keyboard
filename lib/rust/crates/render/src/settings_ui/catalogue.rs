//! Settings screen descriptions. Defaults, ranges and enum membership remain in settings.
#[derive(Clone, Copy, Debug)]
pub enum Kind {
    Heading,
    Toggle,
    Choice(&'static str),
    Slider(&'static str, &'static str),
    Route(&'static str),
}
#[derive(Clone, Copy, Debug)]
pub struct Row {
    pub key: &'static str,
    pub label: &'static str,
    pub summary: &'static str,
    pub kind: Kind,
    pub switch: &'static str,
}
const fn row(
    key: &'static str,
    label: &'static str,
    summary: &'static str,
    kind: Kind,
    switch: &'static str,
) -> Row {
    Row {
        key,
        label,
        summary,
        kind,
        switch,
    }
}
