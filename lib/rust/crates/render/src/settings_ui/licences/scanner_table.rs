/// The state table's row for `ch` in `state`: its own, else the state's default (character 0).
pub(super) fn transition(state: S, ch: i32) -> Option<(A, S)> {
    static INDEX: OnceLock<HashMap<(u8, i32), (A, S)>> = OnceLock::new();
    let index = INDEX.get_or_init(|| {
        let mut index = HashMap::new();
        for &(s, c, a, n) in TABLE {
            index.entry((s as u8, c)).or_insert((a, n));
        }
        index
    });
    index
        .get(&(state as u8, ch))
        .or_else(|| index.get(&(state as u8, 0)))
        .copied()
}
