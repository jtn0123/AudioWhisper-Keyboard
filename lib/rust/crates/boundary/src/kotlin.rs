//! The Kotlin side: one file per class, an `internal object` of `@JvmStatic external fun`s that
//! loads the library first, as the hand-written ones do.

use crate::format::{kdoc, kotlin_declaration};
use crate::{Class, PACKAGE};

/// A generated Kotlin source file.
#[derive(Debug, PartialEq, Eq)]
pub struct KotlinFile {
    /// Where it goes under a Kotlin source root, such as
    /// `com/jtn0123/audiowhisper/rust/ShiftNative.kt`.
    pub path: String,
    pub text: String,
}

/// The Kotlin files for `classes`, in their order.
pub fn kotlin_files(classes: &[Class]) -> Vec<KotlinFile> {
    classes
        .iter()
        .map(|class| KotlinFile {
            path: format!("{}/{}.kt", PACKAGE.replace('.', "/"), class.name),
            text: kotlin_file(class),
        })
        .collect()
}

fn kotlin_file(class: &Class) -> String {
    let mut text = format!(
        "// Generated by lib/rust/crates/boundary from src/declarations/{}.rs. Do not edit.\n",
        class.module
    );
    text.push_str(&format!("package {PACKAGE}\n\n"));
    text.push_str(&kdoc(class.doc, ""));
    text.push_str(&format!("internal object {} {{\n", class.name));
    text.push_str("    init {\n        RustLibrary.load()\n    }\n");
    for method in class.methods {
        let params: Vec<String> = method
            .params
            .iter()
            .map(|(name, param)| format!("{name}: {}", param.kotlin()))
            .collect();
        text.push('\n');
        text.push_str(&kdoc(method.doc, "    "));
        text.push_str(&kotlin_declaration(
            "    ",
            &format!("@JvmStatic external fun {}", method.name),
            &params,
            &format!(": {}", method.returns.kotlin()),
        ));
    }
    text.push_str("}\n");
    text
}
