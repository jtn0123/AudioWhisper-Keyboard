//! The Kotlin side: one file per class, an `object` of `external fun`s that loads the library
//! first, as the hand-written ones did.

use crate::format::{kdoc, kotlin_declaration};
use crate::{Class, Module, Return};

/// A generated Kotlin source file.
#[derive(Debug, PartialEq, Eq)]
pub struct KotlinFile {
    /// Where it goes under a Kotlin source root, such as
    /// `com/jtn0123/audiowhisper/rust/ShiftNative.kt`.
    pub path: String,
    pub text: String,
}

/// The Kotlin files for `classes`, in their order, each with the module it goes in.
pub fn kotlin_files(classes: &[Class]) -> Vec<(Module, KotlinFile)> {
    classes
        .iter()
        .map(|class| {
            let file = KotlinFile {
                path: format!(
                    "{}/{}.kt",
                    class.kotlin.package().replace('.', "/"),
                    class.name
                ),
                text: kotlin_file(class),
            };
            (class.kotlin, file)
        })
        .collect()
}

/// The header of a file generated from `source`, and its package and imports.
pub fn kotlin_header(source: &str, module: Module, imports: &[String]) -> String {
    let mut text = format!(
        "// Generated by lib/rust/crates/boundary from {source}. Do not edit.\npackage {}\n\n",
        module.package()
    );
    for import in imports {
        text.push_str(&format!("import {import}\n"));
    }
    if !imports.is_empty() {
        text.push('\n');
    }
    text
}

/// `kotlin`, a type that may name a class of another package in full, as written once that class
/// is imported, and the import, if any.
pub fn simple_type(kotlin: &str) -> (String, Option<String>) {
    let bare = kotlin.trim_end_matches('?');
    match bare.rfind('.') {
        Some(dot) if !bare.contains('<') => (kotlin[dot + 1..].to_owned(), Some(bare.to_owned())),
        _ => (kotlin.to_owned(), None),
    }
}

fn kotlin_file(class: &Class) -> String {
    let mut imports: Vec<String> = class
        .methods
        .iter()
        .flat_map(|method| method.params.iter())
        .filter_map(|(_, param)| simple_type(&param.kotlin()).1)
        .collect();
    imports.sort();
    imports.dedup();
    let source = format!("src/declarations/{}.rs", class.file());
    let mut text = kotlin_header(&source, class.kotlin, &imports);
    text.push_str(&kdoc(class.doc, ""));
    let visibility = if class.public { "" } else { "internal " };
    text.push_str(&format!("{visibility}object {} {{\n", class.name));
    let load = match class.kotlin {
        Module::Rust => "RustLibrary.load()",
        Module::Kotlin => "System.loadLibrary(\"awnative\")",
    };
    text.push_str(&format!("    init {{\n        {load}\n    }}\n"));
    for method in class.methods {
        let params: Vec<String> = method
            .params
            .iter()
            .map(|(name, param)| {
                let ty = simple_type(&param.kotlin()).0;
                match method.defaults.iter().find(|(param, _)| param == name) {
                    Some((_, value)) => format!("{name}: {ty} = {value}"),
                    None => format!("{name}: {ty}"),
                }
            })
            .collect();
        text.push('\n');
        if !method.doc.is_empty() {
            text.push_str(&kdoc(method.doc, "    "));
        }
        let mut head = String::new();
        if !method.instance {
            head.push_str("@JvmStatic ");
        }
        if method.internal {
            head.push_str("internal ");
        }
        head.push_str(&format!("external fun {}", method.name));
        let tail = if method.returns == Return::Unit {
            String::new()
        } else {
            format!(": {}", method.returns.kotlin())
        };
        text.push_str(&kotlin_declaration("    ", &head, &params, &tail));
    }
    text.push_str("}\n");
    text
}
