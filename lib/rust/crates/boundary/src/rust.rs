//! The Rust side: one file of `extern "system"` entry points for every class, which awnative's
//! build.rs writes into OUT_DIR and its `boundary` module includes. Each entry point reads its
//! arguments, calls the hand-written function, and lets `boundary::call` hand the result back to
//! Kotlin or throw its error.

use crate::format::{
    rust_body, rust_comment, rust_doc, rust_signature, rust_struct_body, rust_use,
};
use crate::{Class, Method, Return, callee, jni_name, rust_param};

/// The most arguments a hand-written function takes one by one, clippy's limit; one with more
/// takes a generated struct of them, after the environment.
const MAX_ARGS: usize = 7;

const HEADER: &str = "\
// Generated by lib/rust/crates/boundary from its declarations, src/declarations. Do not edit:
// awnative's build.rs writes this file into cargo's OUT_DIR, and src/boundary.rs includes it.
";

/// The entry points for every method of `classes`, as one file.
pub fn rust_file(classes: &[Class]) -> String {
    let mut text = String::from(HEADER);
    text.push('\n');
    text.push_str(&rust_use("jni_sys", &jni_imports(classes)));
    text.push('\n');
    text.push_str(&rust_use("crate::boundary", &boundary_imports(classes)));
    text.push('\n');
    text.push_str(&args_module(classes));
    for class in classes {
        let module = class.module;
        let about = format!(
            "{}, declared in src/declarations/{module}.rs, calls crate::{module}.",
            class.name
        );
        text.push('\n');
        text.push_str(&rust_comment(&about, ""));
        for method in class.methods {
            text.push('\n');
            text.push_str(&entry_point(class, method));
        }
    }
    text
}

fn methods(classes: &[Class]) -> impl Iterator<Item = &Method> {
    classes.iter().flat_map(|class| class.methods)
}

/// The `jni_sys` names the entry points for `classes` use, sorted as rustfmt sorts them.
fn jni_imports(classes: &[Class]) -> Vec<String> {
    let mut names = vec!["JNIEnv"];
    for method in methods(classes) {
        names.push(if method.instance { "jobject" } else { "jclass" });
        names.extend(method.params.iter().map(|(_, param)| param.jni()));
        if method.returns != Return::Unit {
            names.push(method.returns.jni());
        }
    }
    sorted(names)
}

/// The names from awnative's `boundary` module the entry points for `classes` use.
fn boundary_imports(classes: &[Class]) -> Vec<String> {
    let mut names = vec!["call"];
    if methods(classes).any(|method| method.returns.rust().contains("Chars")) {
        names.push("Chars");
    }
    sorted(names)
}

/// `names` without repeats, in rustfmt's order: by their characters' codes, so capitals first.
fn sorted(names: Vec<&str>) -> Vec<String> {
    let mut names: Vec<String> = names.into_iter().map(str::to_owned).collect();
    names.sort();
    names.dedup();
    names
}

/// Whether the hand-written function for `method` takes a struct of its arguments.
fn takes_struct(method: &Method) -> bool {
    method.params.len() + usize::from(method.takes_env()) > MAX_ARGS
}

/// The name of `method`'s argument struct: its class's name and its own, as one word.
fn struct_name(class: &Class, method: &Method) -> String {
    let mut chars = method.name.chars();
    let first = chars.next().map(|c| c.to_ascii_uppercase());
    format!(
        "{}{}{}",
        class.name,
        first.into_iter().collect::<String>(),
        chars.as_str()
    )
}

/// The `args` module of argument structs for the methods of `classes` that take one.
fn args_module(classes: &[Class]) -> String {
    let mut structs = String::new();
    let mut jni = Vec::new();
    for class in classes {
        for method in class.methods.iter().filter(|method| takes_struct(method)) {
            let borrows = method
                .params
                .iter()
                .any(|(_, param)| param.field().contains("'a"));
            let lifetime = if borrows { "<'a>" } else { "" };
            structs.push('\n');
            structs.push_str(&rust_doc(
                &format!("The arguments of `{}.{}`.", class.name, method.name),
                "    ",
            ));
            structs.push_str("    #[derive(Debug)]\n");
            structs.push_str(&format!(
                "    pub struct {}{lifetime} {{\n",
                struct_name(class, method)
            ));
            for (name, param) in method.params {
                let field = param.field();
                if field.starts_with('j') {
                    jni.push(param.jni());
                }
                structs.push_str(&format!("        pub {}: {field},\n", rust_param(name)));
            }
            structs.push_str("    }\n");
        }
    }
    let doc = "The arguments of the methods that take more than a Rust function should one by one.";
    let mut text = rust_doc(doc, "");
    if structs.is_empty() {
        text.push_str("pub mod args {}\n");
        return text;
    }
    text.push_str("pub mod args {\n");
    let imports = !jni.is_empty();
    if imports {
        text.push_str(&rust_use("jni_sys", &sorted(jni)).replace("use ", "    use "));
    }
    let structs = if !imports {
        &structs[1..]
    } else {
        &structs[..]
    };
    text.push_str(structs);
    text.push_str("}\n");
    text
}

fn entry_point(class: &Class, method: &Method) -> String {
    let mut text = if method.doc.is_empty() {
        rust_doc(&format!("Calls `{}`.", callee(class, method)), "")
    } else {
        rust_doc(method.doc, "")
    };
    text.push_str("#[unsafe(no_mangle)]\n");
    let this = if method.instance { "jobject" } else { "jclass" };
    let mut params = vec!["env: *mut JNIEnv".to_owned(), format!("_: {this}")];
    for (name, param) in method.params {
        params.push(format!("{}: {}", rust_param(name), param.jni()));
    }
    text.push_str(&rust_signature(
        &format!("pub extern \"system\" fn {}", jni_name(class, method)),
        &params,
        method.returns.jni(),
    ));
    let mut lets = Vec::new();
    let mut fields = Vec::with_capacity(method.params.len());
    for (name, param) in method.params {
        let rust = rust_param(name);
        let (read, arg) = param.read(&rust, name);
        if let Some(read) = read {
            lets.push((rust.clone(), read));
        }
        fields.push((rust, arg));
    }
    text.push_str("    // SAFETY: the JVM passes its environment for this call.\n");
    let returns = method.returns.rust();
    let callee = callee(class, method);
    if takes_struct(method) {
        let name = format!("args::{}", struct_name(class, method));
        let env = method.takes_env();
        text.push_str(&rust_struct_body(
            &returns, &lets, &callee, env, &name, &fields,
        ));
    } else {
        let mut args = Vec::with_capacity(fields.len() + 1);
        if method.takes_env() {
            args.push("env".to_owned());
        }
        args.extend(fields.into_iter().map(|(_, arg)| arg));
        text.push_str(&rust_body(&returns, &lets, &callee, &args));
    }
    text.push_str("}\n");
    text
}
