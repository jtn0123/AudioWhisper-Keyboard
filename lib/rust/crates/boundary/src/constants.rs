//! The Kotlin side of crates/wire's declarations: one file for each declared Kotlin type, in the
//! Gradle module `declarations::WIRE` places it in. An operation set becomes an `enum class` whose
//! entries carry their code; packet fields and the boolean spelling become an `object` of
//! `const val`s; plain codes become a Java class of static constants. The Rust side needs nothing
//! generated: the crates that answer the calls match on wire's constants themselves.

use wire::{Constant, Form, Group, Value};

use crate::format::kdoc;
use crate::kotlin::KotlinFile;

/// A Gradle module that compiles generated Kotlin, and the package its files are in.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Module {
    /// lib/rust, beside the generated `external` objects.
    Rust,
    /// lib/kotlin, the plain JVM library, for the calls it makes itself.
    Kotlin,
}

impl Module {
    pub fn package(self) -> &'static str {
        match self {
            Module::Rust => crate::PACKAGE,
            Module::Kotlin => "org.florisboard.lib.kotlin",
        }
    }
}

/// Declared groups whose Kotlin goes in one module.
#[derive(Debug)]
pub struct Wire {
    pub module: Module,
    /// Whether the Kotlin is `internal` to the module rather than public.
    pub internal: bool,
    pub groups: &'static [&'static Group],
}

/// The generated files for `wire`, one for each declared type, in the order first declared, each
/// with the module it goes in. Plain codes are Java, so Kotlin can import their members with `*`,
/// which it can't from a Kotlin `object`; the rest is Kotlin.
pub fn wire_files(wire: &[Wire]) -> Vec<(Module, KotlinFile)> {
    let mut files = Vec::new();
    for entry in wire {
        let mut types: Vec<&str> = Vec::new();
        for group in entry.groups {
            if !types.contains(&group.kotlin) {
                types.push(group.kotlin);
            }
        }
        for kotlin in types {
            let groups: Vec<&Group> = entry
                .groups
                .iter()
                .copied()
                .filter(|group| group.kotlin == kotlin)
                .collect();
            let first = groups[0];
            for group in &groups {
                assert!(
                    group.form == first.form && group.path == first.path,
                    "{kotlin} is declared in two forms or modules"
                );
                assert!(
                    group.form == Form::Object || groups.len() == 1,
                    "only plain codes can share a type: {kotlin}"
                );
            }
            let java = first.form == Form::Object;
            let file = KotlinFile {
                path: format!(
                    "{}/{kotlin}.{}",
                    entry.module.package().replace('.', "/"),
                    if java { "java" } else { "kt" }
                ),
                text: if java {
                    java_class(entry, &groups)
                } else {
                    kotlin_type(entry, first)
                },
            };
            files.push((entry.module, file));
        }
    }
    files
}

fn header(group: &Group) -> String {
    format!(
        "// Generated by lib/rust/crates/boundary from {}. Do not edit.\n",
        group.path
    )
}

/// The Kotlin for one operation set, packet or flag.
fn kotlin_type(entry: &Wire, group: &Group) -> String {
    let mut text = header(group);
    text.push_str(&format!("package {}\n\n", entry.module.package()));
    text.push_str(&kdoc(group.doc, ""));
    let visibility = if entry.internal { "internal " } else { "" };
    if group.form == Form::Enum {
        let kind = match group.constants[0].value {
            Value::Int(_) => "Int",
            Value::Text(_) => "String",
        };
        text.push_str(&format!(
            "{visibility}enum class {}(val code: {kind}) {{\n",
            group.kotlin
        ));
        for constant in group.constants {
            text.push_str(&doc(constant));
            text.push_str(&format!(
                "    {}({}),\n",
                constant.name,
                literal(constant.value)
            ));
        }
    } else {
        text.push_str(&format!("{visibility}object {} {{\n", group.kotlin));
        for constant in group.constants {
            text.push_str(&doc(constant));
            text.push_str(&format!(
                "    const val {} = {}\n",
                constant.name,
                literal(constant.value)
            ));
        }
        if group.form == Form::Fields {
            text.push_str(&kdoc("How many fields the packet has.", "    "));
            text.push_str(&format!("    const val SIZE = {}\n", group.constants.len()));
            text.push_str(ROW_FUNCTION);
        }
        if group.form == Form::Flag {
            text.push_str(FLAG_FUNCTIONS);
        }
    }
    text.push_str("}\n");
    text
}

/// A Java class of static constants for `groups`, which share its name; each group opens with a
/// comment of its doc.
fn java_class(entry: &Wire, groups: &[&Group]) -> String {
    let first = groups[0];
    let mut text = header(first);
    text.push_str(&format!("package {};\n\n", entry.module.package()));
    let about = format!(
        "Codes declared in `{}`, in groups whose values never clash.",
        first.path
    );
    text.push_str(&kdoc(&about, ""));
    let visibility = if entry.internal { "" } else { "public " };
    text.push_str(&format!(
        "{visibility}final class {0} {{\n    private {0}() {{}}\n",
        first.kotlin
    ));
    for group in groups {
        text.push('\n');
        text.push_str(&kdoc(group.doc, "    ").replacen("/**", "/*", 1));
        for constant in group.constants {
            let kind = match constant.value {
                Value::Int(_) => "int",
                Value::Text(_) => "String",
            };
            text.push_str(&doc(constant));
            text.push_str(&format!(
                "    public static final {kind} {} = {};\n",
                constant.name,
                literal(constant.value)
            ));
        }
    }
    text.push_str("}\n");
    text
}

/// What a packet's fields object adds: a builder that sets each field by name, once.
const ROW_FUNCTION: &str = "
    /** A row of [fields], each given once by its position. */
    fun row(vararg fields: Pair<Int, String>): Array<String> {
        val row = arrayOfNulls<String>(SIZE)
        for ((field, value) in fields) {
            check(row[field] == null) { \"field $field given twice\" }
            row[field] = value
        }
        return Array(SIZE) { checkNotNull(row[it]) { \"field $it missing\" } }
    }
";

/// What a boolean flag object adds to its `TRUE` and `FALSE`.
const FLAG_FUNCTIONS: &str = "
    /** [value] as it crosses. */
    fun encode(value: Boolean): String = if (value) TRUE else FALSE

    /** Whether [value] is [TRUE]. Anything else, [FALSE] included, is false. */
    fun decode(value: String): Boolean = value == TRUE
";

fn doc(constant: &Constant) -> String {
    if constant.doc.trim().is_empty() {
        String::new()
    } else {
        kdoc(constant.doc, "    ")
    }
}

/// `value` as a Kotlin or Java literal. wire's check keeps names to characters a string literal
/// can hold as they are.
fn literal(value: Value) -> String {
    match value {
        Value::Int(value) => value.to_string(),
        Value::Text(text) => format!("\"{text}\""),
    }
}

