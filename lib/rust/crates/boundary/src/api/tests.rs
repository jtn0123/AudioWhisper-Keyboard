#[test]
fn generation_is_deterministic() {
    assert_eq!(api_files(APIS, CLASSES), api_files(APIS, CLASSES));
    assert_eq!(type_files(TYPES), type_files(TYPES));
}

#[test]
fn the_kotlin_fits_the_style() {
    let files = api_files(APIS, CLASSES)
        .into_iter()
        .chain(type_files(TYPES));
    for (_, file) in files.chain(api_files(EXAMPLES, NATIVE)) {
        // A record with no body ends its file with its parameters.
        let ends = file.text.ends_with("}\n") || file.text.ends_with(")\n");
        assert!(ends && !file.text.contains("\n\n\n"), "{}", file.path);
        for line in file.text.lines() {
            assert!(line.len() <= 120, "{}: {line}", file.path);
            assert_eq!(line.trim_end(), line, "{}", file.path);
        }
    }
}

#[test]
fn an_example_comes_out_as_written() {
    let rules = "\
// Generated by lib/rust/crates/boundary from src/declarations/example.rs. Do not edit.
package com.jtn0123.audiowhisper.rust

/** Rules. */
object ExampleRules {
    /** A case. */
    enum class Case { LOWER, UPPER }

    /** No limit. */
    const val NONE = -1

    val limit: Int = ExampleNative.limit()

    val names: List<String> by lazy { ExampleNative.names().asList() }

    /** The case of `word`. */
    fun case(word: String): Case = Case.entries[ExampleNative.caseOf(word)]
}
";
    let store = "\
// Generated by lib/rust/crates/boundary from src/declarations/example.rs. Do not edit.
package com.jtn0123.audiowhisper.rust

import java.lang.ref.Reference

/** A store. */
class ExampleStore(capacity: Int = 16) {
    internal val handle = ExampleNative.create(capacity)

    init {
        RustLibrary.cleaner.register(this, Free(handle))
    }

    fun add(word: String, op: ExampleOp): Boolean =
        ExampleNative.add(handle, word, op.code).also { Reference.reachabilityFence(this) }

    fun words(
        other: ExampleStore?,
        previous: List<String>,
        aVeryLongParameterNameIndeed: String?,
        anotherVeryLongParameterName: FloatArray,
    ): List<String> =
        ExampleNative.words(
            handle,
            other?.handle ?: 0L,
            previous.toTypedArray(),
            aVeryLongParameterNameIndeed,
            anotherVeryLongParameterName,
        ).asList().also { Reference.reachabilityFence(other); Reference.reachabilityFence(this) }

    private class Free(private val handle: Long) : Runnable {
        override fun run() = ExampleNative.free(handle)
    }

    companion object {
        val limit: Int = ExampleNative.limit()
    }
}
";
    let files = api_files(EXAMPLES, NATIVE);
    assert_eq!(
        files[0].1.path,
        "com/jtn0123/audiowhisper/rust/ExampleRules.kt"
    );
    assert_eq!(files[0].1.text, rules);
    assert_eq!(files[1].1.text, store);
}

#[test]
fn a_closeable_class_locks_and_converts() {
    const SESSION: Api = Api {
        name: "ExampleSession",
        doc: "A session.",
        module: "example",
        native: "ExampleNative",
        shape: Shape::Handle(Handle {
            free: "free",
            close: true,
            synchronized: true,
            lend: true,
            ..HANDLE
        }),
        members: &[
            Member {
                name: "open",
                call: "create",
                companion: true,
                result: Out::NullableWrap("ExampleSession"),
                ..MEMBER
            },
            Member {
                name: "add",
                args: &[
                    arg("word", ArgKind::Fixed("\"\"")),
                    arg("op", ArgKind::Ordinal("Mode")),
                ],
                result: Out::Wrap("Added"),
                ..MEMBER
            },
            Member {
                name: "pick",
                call: "words",
                args: &[arg("other", ArgKind::Handle("ExampleSession"))],
                ..MEMBER
            },
            Member {
                name: "case",
                call: "caseOf",
                companion: true,
                result: Out::NullableEntry("Case"),
                ..MEMBER
            },
        ],
        companion: true,
        ..API
    };
    let text = &api_files(&[SESSION], NATIVE)[0].1.text;
    for expected in [
        "class ExampleSession internal constructor(handle: Long) : AutoCloseable {\n",
        "    internal var handle = handle\n        private set\n",
        "    private val cleanable = RustLibrary.cleaner.register(this, Free(handle))\n",
        "    @Synchronized\n    fun add(op: Mode): Added = Added(ExampleNative.add(handle, \"\", op.ordinal))\n",
        "            other.handle,\n            previous,\n",
        "        ).also { Reference.reachabilityFence(other) }\n",
        "    @Synchronized\n    override fun close() {\n        handle = 0\n        cleanable.clean()\n",
        "        internal fun <T> lend(owner: ExampleSession?, action: (Long) -> T): T =\n            \
         if (owner == null) action(-1L) else synchronized(owner) { action(owner.handle) }\n",
        "        fun open(capacity: Int): ExampleSession? =\n            \
         ExampleNative.create(capacity).let { if (it == 0L) null else ExampleSession(it) }\n",
        "\n        fun case(word: String): Case? = \
         ExampleNative.caseOf(word).let { if (it < 0) null else Case.entries[it] }\n",
    ] {
        assert!(text.contains(expected), "{expected}\nnot in\n{text}");
    }
}

#[test]
fn a_class_keeps_a_property_and_borrows_a_lent_handle() {
    const LENDER: Api = Api {
        name: "ExampleSession",
        module: "example",
        native: "ExampleNative",
        shape: Shape::Handle(Handle {
            free: "free",
            close: true,
            synchronized: true,
            lend: true,
            ..HANDLE
        }),
        ..API
    };
    const KEEPER: Api = Api {
        name: "ExampleKeeper",
        module: "example",
        native: "ExampleNative",
        shape: Shape::Handle(Handle {
            keeps: &["private val word: String"],
            create: "create",
            free: "free",
            ..HANDLE
        }),
        members: &[
            Member {
                name: "add",
                args: &[arg("word", ArgKind::Fixed("word"))],
                ..MEMBER
            },
            Member {
                name: "pick",
                call: "words",
                args: &[
                    arg("other", ArgKind::Lent("ExampleSession")),
                    arg("previous", ArgKind::List),
                ],
                result: Out::List,
                ..MEMBER
            },
        ],
        ..API
    };
    let files = api_files(&[LENDER, KEEPER], NATIVE);
    let keeper = &files[1].1.text;
    for expected in [
        "class ExampleKeeper(private val word: String, capacity: Int) {\n",
        "    fun add(op: Int): Boolean = \
         ExampleNative.add(handle, word, op).also { Reference.reachabilityFence(this) }\n",
        "    ): List<String> =\n        ExampleSession.lend(other) {\n            \
         ExampleNative.words(\n                handle,\n                it,\n                \
         previous.toTypedArray(),\n",
        "            )\n        }.asList().also { Reference.reachabilityFence(this) }\n",
    ] {
        assert!(keeper.contains(expected), "{expected}\nnot in\n{keeper}");
    }
    let one = Expr {
        before: String::new(),
        call: "N.f".to_owned(),
        args: vec!["handle".to_owned(), "it".to_owned()],
        after: ".asList()".to_owned(),
        lend: Some("S.lend(s) {".to_owned()),
    };
    assert_eq!(one.line(), "S.lend(s) { N.f(handle, it) }.asList()");
}

