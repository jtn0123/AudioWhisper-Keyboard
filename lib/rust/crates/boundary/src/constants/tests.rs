use std::collections::HashSet;

use super::*;
use crate::declarations::{CLASSES, WIRE};
use crate::kotlin_files;

mod example {
    wire::declare! {
        /// What an example does.
        pub const OPS: enum ExampleOp(str) {
            /// Begins.
            BEGIN = "begin",
            END = "end",
        }
    }

    pub mod point {
        wire::declare! {
            /// A point.
            pub const FIELDS: fields ExamplePoint {
                /// Across.
                X,
                Y,
            }
        }
    }

    wire::declare! {
        /// Codes an example reads.
        pub const READ: object ExampleCodes(i32) {
            /// Pressed.
            DOWN = 0,
            UP = 1,
        }
    }

    wire::declare! {
        /// Codes it writes.
        pub const WRITTEN: object ExampleCodes(i32) {
            MOVE = 20,
        }
    }

    pub const GROUPS: &[&wire::Group] = &[&OPS, &point::FIELDS, &READ, &WRITTEN];
}

const EXAMPLE: &[Wire] = &[Wire {
    module: Module::Rust,
    internal: false,
    groups: example::GROUPS,
}];

#[test]
fn generation_is_deterministic() {
    assert_eq!(wire_files(WIRE), wire_files(WIRE));
    let mut paths = HashSet::new();
    for (module, file) in kotlin_files(CLASSES).into_iter().chain(wire_files(WIRE)) {
        assert!(paths.insert((module, file.path.clone())), "{}", file.path);
    }
}

#[test]
fn the_kotlin_fits_the_style() {
    for (_, file) in wire_files(WIRE).iter().chain(&wire_files(EXAMPLE)) {
        assert!(file.text.ends_with("}\n") && !file.text.contains("\n\n\n"));
        for line in file.text.lines() {
            assert!(line.len() <= 120, "{}: {line}", file.path);
            assert_eq!(line.trim_end(), line, "{}", file.path);
            assert!(!line.contains('\t'), "{}", file.path);
        }
    }
}

/// Whether `name` is a constant's name: ASCII capitals, digits and underscores, from a capital.
fn screaming(name: &str) -> bool {
    name.starts_with(|c: char| c.is_ascii_uppercase())
        && name
            .chars()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_')
}

#[test]
fn declared_names_are_plain_and_distinct() {
    let classes: HashSet<_> = CLASSES.iter().map(|class| class.name).collect();
    for entry in WIRE {
        // Constants of one Kotlin type, which may gather several groups.
        let mut names: Vec<(&str, HashSet<&str>)> = Vec::new();
        for group in entry.groups {
            let kotlin = group.kotlin;
            assert!(
                kotlin.starts_with(|c: char| c.is_ascii_uppercase())
                    && kotlin.chars().all(|c| c.is_ascii_alphanumeric())
                    && !classes.contains(kotlin),
                "{kotlin}"
            );
            assert!(!group.doc.trim().is_empty(), "{kotlin} needs a doc");
            assert!(group.path.starts_with("wire::"), "{}", group.path);
            let at = names.iter().position(|(name, _)| *name == kotlin);
            let at = at.unwrap_or_else(|| {
                names.push((kotlin, HashSet::new()));
                names.len() - 1
            });
            for constant in group.constants {
                let name = constant.name;
                let reserved = name == "SIZE" && group.form == Form::Fields;
                assert!(screaming(name) && !reserved, "{kotlin}.{name}");
                assert!(names[at].1.insert(name), "{kotlin}.{name} twice");
            }
        }
    }
}

#[test]
fn an_example_comes_out_as_written() {
    let files = wire_files(EXAMPLE);
    let paths: Vec<_> = files.iter().map(|(_, file)| file.path.as_str()).collect();
    let package = "com/jtn0123/audiowhisper/rust";
    assert_eq!(
        paths,
        [
            format!("{package}/ExampleOp.kt"),
            format!("{package}/ExamplePoint.kt"),
            format!("{package}/ExampleCodes.java"),
        ]
    );
    let source = "Do not edit.\npackage com.jtn0123.audiowhisper.rust\n\n";
    let path = "// Generated by lib/rust/crates/boundary from boundary::constants::tests::example";
    assert_eq!(
        files[0].1.text,
        format!("{path}. {source}")
            + "\
/** What an example does. */
enum class ExampleOp(val code: String) {
    /** Begins. */
    BEGIN(\"begin\"),
    END(\"end\"),
}
"
    );
    assert_eq!(
        files[1].1.text,
        format!("{path}::point. {source}")
            + "\
/** A point. */
object ExamplePoint {
    /** Across. */
    const val X = 0
    const val Y = 1
    /** How many fields the packet has. */
    const val SIZE = 2

    /** A row of [fields], each given once by its position. */
    fun row(vararg fields: Pair<Int, String>): Array<String> {
        val row = arrayOfNulls<String>(SIZE)
        for ((field, value) in fields) {
            check(row[field] == null) { \"field $field given twice\" }
            row[field] = value
        }
        return Array(SIZE) { checkNotNull(row[it]) { \"field $it missing\" } }
    }
}
"
    );
    assert_eq!(
        files[2].1.text,
        format!("{path}. Do not edit.\npackage com.jtn0123.audiowhisper.rust;\n\n")
            + "\
/** Codes declared in `boundary::constants::tests::example`, in groups whose values never clash. */
public final class ExampleCodes {
    private ExampleCodes() {}

    /* Codes an example reads. */
    /** Pressed. */
    public static final int DOWN = 0;
    public static final int UP = 1;

    /* Codes it writes. */
    public static final int MOVE = 20;
}
"
    );
    assert_eq!((example::point::X, example::point::SIZE), (0, 2));
}
